/**
 * Compose the browser half into the Web client's module format.
 *
 * The client module loader only ever calls a factory: a served package's browser
 * file must be one self-contained script that registers itself as
 * `window.__ModuleLoader__.load({ id, factory })` and returns `{ apply, inject }`.
 *
 * There is no bundler here: `src/client.mjs` has no imports, uses the loader's
 * React through the factory's `require`, and only needs its leading `export`
 * keywords stripped before being wrapped.
 *
 * @module dsh-cache-probe/scripts/bundle
 */

import { readFile } from 'node:fs/promises'
import { join } from 'node:path'

/** Module id the browser factory registers under; must be the package name. */
export const PACKAGE_NAME = 'dsh-cache-probe'

/**
 * Remove the ESM plumbing the factory replaces.
 * @param source - module text.
 * @returns the same text without import statements or leading `export ` keywords.
 */
function stripModuleSyntax(source) {
  const kept = []
  let dropping = false
  for (const line of source.split('\n')) {
    if (!dropping && /^[ \t]*import\b/u.test(line)) {
      dropping = !/['"][^'"]*['"];?[ \t]*$/u.test(line)
      continue
    }
    if (dropping) {
      if (/['"][^'"]*['"];?[ \t]*$/u.test(line)) dropping = false
      continue
    }
    kept.push(line)
  }
  const stripped = kept.join('\n').replace(/^export[ \t]+(?=(?:function|const|let|class)\b)/gmu, '')
  if (/^[ \t]*import\b/mu.test(stripped)) throw new Error('build: an import statement survived inlining')
  return stripped
}

/**
 * Indent every non-empty line.
 * @param text - source text.
 * @param width - spaces to prepend.
 * @returns the indented text.
 */
function indent(text, width) {
  const pad = ' '.repeat(width)
  return text
    .split('\n')
    .map((line) => (line.trim() === '' ? '' : pad + line))
    .join('\n')
}

/**
 * Build the browser bundle text.
 * @param root - package root directory.
 * @returns the bundle text and the package version baked into it.
 */
export async function bundleClient(root) {
  const manifest = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
  if (manifest.name !== PACKAGE_NAME) {
    throw new Error(`build: package.json names ${JSON.stringify(manifest.name)}, expected ${PACKAGE_NAME}`)
  }
  const version = String(manifest.version ?? '0.0.0')
  const modules = []
  for (const file of ['options.mjs', 'stats.mjs', 'client.mjs']) {
    modules.push(stripModuleSyntax(await readFile(join(root, 'src', file), 'utf8')).trimEnd())
  }
  const client = modules.join('\n\n')

  const text = [
    '// Generated by scripts/build.mjs — edit src/client.mjs and rebuild (npm run build).',
    'window.__ModuleLoader__.load({',
    `  id: ${JSON.stringify(PACKAGE_NAME)},`,
    '  factory: (require) => {',
    '    var module = { exports: {} };',
    '    var exports = module.exports;',
    '    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });',
    '    const React = require("react");',
    '    const h = React.createElement;',
    `    const __DSH_PLUGIN_VERSION__ = ${JSON.stringify(version)};`,
    indent(client, 4),
    '',
    '    exports.apply = apply;',
    '    exports.inject = inject;',
    '    return module.exports;',
    '  },',
    '});',
    '',
  ].join('\n')
  return { text, version }
}